const getDeterministicAvatar = (seed) => {
  if (!seed) return RANDOM_AVATARS[0];
  let hash = 0;
  for (let i = 0; i < seed.length; i++) {
    hash = seed.charCodeAt(i) + ((hash << 5) - hash);
  }
  const index = Math.abs(hash) % RANDOM_AVATARS.length;
  return RANDOM_AVATARS[index];
};

